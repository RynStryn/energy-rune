static void DrawPattern(LEDStrip_t* strip,
                        const uint8_t pattern[PANEL_ROWS][PANEL_COLS],
                        Color_t color) {
  for (uint8_t y = 0; y < PANEL_ROWS; y++) {
    for (uint8_t x = 0; x < PANEL_COLS; x++) {
      if (pattern[y][x]) {
        strip->panel[y][x].r = color.r;
        strip->panel[y][x].g = color.g;
        strip->panel[y][x].b = color.b;
        strip->panel[y][x].enable = 1;
      }
    }
  }
}

void WaterFlow_Init(LEDStrip_t* strip) {
  strip->water_flow_active = 0;
  memset(strip->panel, 0, sizeof(strip->panel));
}

void WaterFlow_Start(LEDStrip_t* strip, Color_t fill) {
  memset(strip->panel, 0, sizeof(strip->panel));
  for (uint8_t y = 0; y < PANEL_ROWS; y++) {
    strip->panel[y][0].r = fill.r;
    strip->panel[y][0].g = fill.g;
    strip->panel[y][0].b = fill.b;
    strip->panel[y][0].enable = 1;
  }
  strip->water_flow_active = 1;
  strip->panel_change = 1;
  WaterFlow_Display(strip);
}

void WaterFlow_StartArrow(LEDStrip_t* strip, Color_t fill) {
  memset(strip->panel, 0, sizeof(strip->panel));
  DrawPattern(strip, arrow_matrix, fill);
  strip->water_flow_active = 1;
  strip->panel_change = 1;
  WaterFlow_Display(strip);
}

void WaterFlow_Stop(LEDStrip_t* strip) {
  strip->water_flow_active = 0;
  memset(strip->panel, 0, sizeof(strip->panel));
  strip->panel_change = 1;
}

void WaterFlow_Step(LEDStrip_t* strip) {
  if (!strip->water_flow_active)
    return;

  for (uint8_t y = 0; y < PANEL_ROWS; y++) {
    Led_t last = strip->panel[y][PANEL_COLS - 1];
    for (int16_t x = PANEL_COLS - 1; x > 0; x--) {
      strip->panel[y][x] = strip->panel[y][x - 1];
    }
    strip->panel[y][0] = last;
  }
  strip->panel_change = 1;
}

void WaterFlow_Display(LEDStrip_t* strip) {
  Target_LoadLEDPtr(strip);
}

uint8_t WaterFlow_IsActive(LEDStrip_t* strip) {
  return strip->water_flow_active;
}