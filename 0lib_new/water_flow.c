void WaterFlow_Init(void)
{
    memset(g_fb, 0, sizeof(g_fb));
    g_active = 0;
}

void WaterFlow_Start(Color_t fill)
{
    for (uint8_t y = 0; y < PANEL_ROWS; y++)
    {
        for (uint8_t x = 0; x < PANEL_COLS; x++)
        {
            g_fb[y][x] = (x == 0) ? fill : COLOR_BLACK;
        }
    }
    g_active = 1;
    WaterFlow_Display();
}

void WaterFlow_StartArrow(Color_t fill)
{
    for (uint8_t y = 0; y < PANEL_ROWS; y++)
    {
        for (uint8_t x = 0; x < PANEL_COLS; x++)
        {
            g_fb[y][x] = arrow_matrix[y][x] ? fill : COLOR_BLACK;
        }
    }
    g_active = 1;
    WaterFlow_Display();
}

void WaterFlow_Stop(void)
{
    g_active = 0;
    memset(g_fb, 0, sizeof(g_fb));
    Panel_Clear();
    Panel_load2led();
}

void WaterFlow_Step(void)
{
    if (!g_active)
        return;
    for (uint8_t y = 0; y < PANEL_ROWS; y++)
    {
        Color_t last = g_fb[y][PANEL_COLS - 1];
        for (int16_t x = PANEL_COLS - 1; x > 0; x--)
        {
            g_fb[y][x] = g_fb[y][x - 1];
        }
        g_fb[y][0] = last;
    }
}

void WaterFlow_Display(void)
{
    if (!g_active)
        return;
    Panel_Clear();
    for (uint8_t y = 0; y < PANEL_ROWS; y++)
    {
        for (uint8_t x = 0; x < PANEL_COLS; x++)
        {
            Color_t c = g_fb[y][x];
            if (c.r || c.g || c.b)
            {
                Panel_SetLed(x, y, c.r, c.g, c.b);
            }
        }
    }
    Panel_load2led();
}

uint8_t WaterFlow_IsActive(void) { return g_active; }
